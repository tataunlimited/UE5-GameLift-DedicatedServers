// --- PUBLIC ENTRY POINTS ---

void UClientSaveManager::SavePlayerStateToS3(USaveGame* PlayerSaveObject, USaveGame* HomeAreaSaveObject)
{
	if (!IsValid(PlayerSaveObject) || !IsValid(HomeAreaSaveObject))
	{
		UE_LOG(LogDedicatedServers, Error, TEXT("SavePlayerStateToS3: A SaveGame object was null."));
		OnSaveToS3Complete.Broadcast(false);
		return;
	}

	TempPlayerSerializedData = USaveSystemHelpers::SerializeSaveGameObject(PlayerSaveObject);
	TempHomeAreaSerializedData = USaveSystemHelpers::SerializeSaveGameObject(HomeAreaSaveObject);

	if (TempPlayerSerializedData.Num() == 0 || TempHomeAreaSerializedData.Num() == 0)
	{
		UE_LOG(LogDedicatedServers, Error, TEXT("SavePlayerStateToS3: Serialization failed."));
		OnSaveToS3Complete.Broadcast(false);
		return;
	}
	
	RequestClientUploadURLs();
}

void UClientSaveManager::LoadPlayerStateFromS3()
{
	TempLoadedPlayerSave = nullptr;
	TempLoadedHomeAreaSave = nullptr;
	PendingDownloads = 0;
	RequestClientDownloadURLs();
}

void UClientSaveManager::TriggerBlueprintClientSave(AGameModeBase* GameMode)
{
	CreateAndSaveLocalData(GameMode);
}

// --- OVERRIDDEN S3 HANDLERS ---

FString UClientSaveManager::GetUsername() const
{
	UDSLocalPlayerSubsystem* LocalPlayerSubsystem = GetDSLocalPlayerSubsystem();
	if (!IsValid(LocalPlayerSubsystem)) return "";
	return LocalPlayerSubsystem->Username;
}

void UClientSaveManager::HandleUploadResponse(FHttpRequestPtr Request, FHttpResponsePtr Response, bool bWasSuccessful)
{
	if (!bWasSuccessful || !Response.IsValid() || !EHttpResponseCodes::IsOk(Response->GetResponseCode()))
	{
		UE_LOG(LogDedicatedServers, Error, TEXT("Client S3 upload failed."));
		OnSaveToS3Complete.Broadcast(false);
		return;
	}

	PendingUploads--;
	if (PendingUploads <= 0)
	{
		// Both client uploads are finished, now confirm the save with our backend.
		ConfirmClientS3Upload();
	}
}

void UClientSaveManager::HandleDownloadResponse(FHttpRequestPtr Request, FHttpResponsePtr Response, bool bWasSuccessful)
{
	if (!bWasSuccessful || !Response.IsValid() || !EHttpResponseCodes::IsOk(Response->GetResponseCode()))
	{
		UE_LOG(LogDedicatedServers, Error, TEXT("Client S3 download failed."));
		OnLoadFromS3Complete.Broadcast(false, nullptr, nullptr);
		return;
	}

	const TArray<uint8>& DownloadedData = Response->GetContent();
	
	FString RequestURL = Request->GetURL();
    // NOTE: The substrings "playerData" and "homeAreaData" are assumed to be part of the pre-signed S3 URLs
    // generated by your backend API to help differentiate them.
	if (RequestURL.Contains("playerData")) 
	{
		TempLoadedPlayerSave = USaveSystemHelpers::DeserializeSaveGameObject(PlayerSaveGameClass, DownloadedData);
	}
	else if (RequestURL.Contains("homeAreaData"))
	{
		TempLoadedHomeAreaSave = USaveSystemHelpers::DeserializeSaveGameObject(HomeAreaSaveGameClass, DownloadedData);
	}

	PendingDownloads--;
	if (PendingDownloads <= 0)
	{
		// Both client downloads are complete, broadcast the final result.
		bool bLoadSuccess = IsValid(TempLoadedPlayerSave) && IsValid(TempLoadedHomeAreaSave);
		OnLoadFromS3Complete.Broadcast(bLoadSuccess, TempLoadedHomeAreaSave, TempLoadedPlayerSave);
	}
}


// --- CLIENT SAVE PROCESS ---

void UClientSaveManager::RequestClientUploadURLs()
{
    UDSLocalPlayerSubsystem* LocalPlayerSubsystem = GetDSLocalPlayerSubsystem();
    if (!IsValid(LocalPlayerSubsystem)) { OnSaveToS3Complete.Broadcast(false); return; }
    const FString AccessToken = LocalPlayerSubsystem->GetAuthResult().AccessToken;

    TSharedPtr<FJsonObject> JsonObject = MakeShareable(new FJsonObject());
    JsonObject->SetStringField(TEXT("accessToken"), AccessToken);

    TArray<TSharedPtr<FJsonValue>> SaveTypesArray;
    SaveTypesArray.Add(MakeShareable(new FJsonValueString(TEXT("player"))));
    SaveTypesArray.Add(MakeShareable(new FJsonValueString(TEXT("homeArea"))));
    JsonObject->SetArrayField(TEXT("saveTypes"), SaveTypesArray);
    
    FString JsonPayload;
    TSharedRef<TJsonWriter<>> Writer = TJsonWriterFactory<>::Create(&JsonPayload);
    FJsonSerializer::Serialize(JsonObject.ToSharedRef(), Writer);

    TSharedRef<IHttpRequest> Request = FHttpModule::Get().CreateRequest();
    const FString APIUrl = APIData->GetAPIEndpoint(DedicatedServerTags::PlayerSaveAPI::RequestUploadURL);
    Request->OnProcessRequestComplete().BindUObject(this, &UClientSaveManager::OnRequestClientUploadURLsResponse);
    Request->SetURL(APIUrl);
    Request->SetVerb(TEXT("POST"));
    Request->SetHeader("Content-Type", "application/json");
    Request->SetContentAsString(JsonPayload);
    Request->ProcessRequest();
}

void UClientSaveManager::OnRequestClientUploadURLsResponse(FHttpRequestPtr Request, FHttpResponsePtr Response, bool bWasSuccessful)
{
    if (!bWasSuccessful || !Response.IsValid() || !EHttpResponseCodes::IsOk(Response->GetResponseCode())) {
        OnSaveToS3Complete.Broadcast(false);
        return;
    }

    TSharedPtr<FJsonObject> OuterJsonObject;
    TSharedRef<TJsonReader<>> OuterReader = TJsonReaderFactory<>::Create(Response->GetContentAsString());
    if (FJsonSerializer::Deserialize(OuterReader, OuterJsonObject) && OuterJsonObject.IsValid())
    {
        FString BodyString;
        if (OuterJsonObject->TryGetStringField(TEXT("body"), BodyString))
        {
            TSharedPtr<FJsonObject> InnerJsonObject;
            TSharedRef<TJsonReader<>> InnerReader = TJsonReaderFactory<>::Create(BodyString);
            if (FJsonSerializer::Deserialize(InnerReader, InnerJsonObject) && InnerJsonObject.IsValid())
            {
                const TArray<TSharedPtr<FJsonValue>>* UrlsJsonArray;
                if (InnerJsonObject->TryGetArrayField(TEXT("urls"), UrlsJsonArray))
                {
                    FString PlayerUploadURL, HomeAreaUploadURL;

                    for (const TSharedPtr<FJsonValue>& UrlValue : *UrlsJsonArray)
                    {
                        const TSharedPtr<FJsonObject> UrlObject = UrlValue->AsObject();
                        if (UrlObject.IsValid())
                        {
                            FString SaveType = UrlObject->GetStringField(TEXT("saveType"));
                            if (SaveType == TEXT("player")) {
                                PlayerUploadURL = UrlObject->GetStringField(TEXT("uploadUrl"));
                                TempPlayerS3Key = UrlObject->GetStringField(TEXT("s3Key"));
                            } else if (SaveType == TEXT("homeArea")) {
                                HomeAreaUploadURL = UrlObject->GetStringField(TEXT("uploadUrl"));
                                TempHomeAreaS3Key = UrlObject->GetStringField(TEXT("s3Key"));
                            }
                        }
                    }

                    if (!PlayerUploadURL.IsEmpty() && !HomeAreaUploadURL.IsEmpty()) {
                        PendingUploads = 2;
                        UploadDataToS3(PlayerUploadURL, TempPlayerSerializedData);
                        UploadDataToS3(HomeAreaUploadURL, TempHomeAreaSerializedData);
                        return; // Success
                    }
                }
            }
        }
    }
    
    OnSaveToS3Complete.Broadcast(false);
}

void UClientSaveManager::ConfirmClientS3Upload()
{
    UDSLocalPlayerSubsystem* LocalPlayerSubsystem = GetDSLocalPlayerSubsystem();
    if (!IsValid(LocalPlayerSubsystem))
    {
	    OnSaveToS3Complete.Broadcast(false); return;
    }
	
    const FString AccessToken = LocalPlayerSubsystem->GetAuthResult().AccessToken;

    TSharedPtr<FJsonObject> JsonObject = MakeShareable(new FJsonObject());
    JsonObject->SetStringField(TEXT("accessToken"), AccessToken);
    JsonObject->SetStringField(TEXT("playerS3Key"), TempPlayerS3Key);
    JsonObject->SetStringField(TEXT("homeAreaS3Key"), TempHomeAreaS3Key);

    FString JsonPayload;
    TSharedRef<TJsonWriter<>> Writer = TJsonWriterFactory<>::Create(&JsonPayload);
    FJsonSerializer::Serialize(JsonObject.ToSharedRef(), Writer);

    TSharedRef<IHttpRequest> Request = FHttpModule::Get().CreateRequest();
    const FString APIUrl = APIData->GetAPIEndpoint(DedicatedServerTags::PlayerSaveAPI::ConfirmSave);
    Request->OnProcessRequestComplete().BindUObject(this, &UClientSaveManager::OnConfirmClientS3UploadResponse);
    Request->SetURL(APIUrl);
    Request->SetVerb(TEXT("POST"));
    Request->SetHeader("Content-Type", "application/json");
    Request->SetContentAsString(JsonPayload);
    Request->ProcessRequest();
}

void UClientSaveManager::OnConfirmClientS3UploadResponse(FHttpRequestPtr Request, FHttpResponsePtr Response, bool bWasSuccessful)
{
	bool bSuccess = bWasSuccessful && Response.IsValid() && EHttpResponseCodes::IsOk(Response->GetResponseCode());
	OnSaveToS3Complete.Broadcast(bSuccess);
}

// --- CLIENT LOAD PROCESS ---

void UClientSaveManager::RequestClientDownloadURLs()
{
    UDSLocalPlayerSubsystem* LocalPlayerSubsystem = GetDSLocalPlayerSubsystem();
    if (!IsValid(LocalPlayerSubsystem)) { OnLoadFromS3Complete.Broadcast(false, nullptr, nullptr); return; }
    const FString AccessToken = LocalPlayerSubsystem->GetAuthResult().AccessToken;

    TSharedPtr<FJsonObject> JsonObject = MakeShareable(new FJsonObject());
    JsonObject->SetStringField(TEXT("accessToken"), AccessToken);

    FString JsonPayload;
    TSharedRef<TJsonWriter<>> Writer = TJsonWriterFactory<>::Create(&JsonPayload);
    FJsonSerializer::Serialize(JsonObject.ToSharedRef(), Writer);

    TSharedRef<IHttpRequest> Request = FHttpModule::Get().CreateRequest();
    const FString APIUrl = APIData->GetAPIEndpoint(DedicatedServerTags::PlayerSaveAPI::RequestDownloadURL);
    Request->OnProcessRequestComplete().BindUObject(this, &UClientSaveManager::OnRequestClientDownloadURLsResponse);
    Request->SetURL(APIUrl);
    Request->SetVerb(TEXT("POST"));
    Request->SetHeader("Content-Type", "application/json");
    Request->SetContentAsString(JsonPayload);
    Request->ProcessRequest();
}

void UClientSaveManager::OnRequestClientDownloadURLsResponse(FHttpRequestPtr Request, FHttpResponsePtr Response, bool bWasSuccessful)
{
    if (!bWasSuccessful || !Response.IsValid() || !EHttpResponseCodes::IsOk(Response->GetResponseCode())) {
        OnLoadFromS3Complete.Broadcast(false, nullptr, nullptr);
        return;
    }
    
    TSharedPtr<FJsonObject> OuterJsonObject;
    TSharedRef<TJsonReader<>> OuterReader = TJsonReaderFactory<>::Create(Response->GetContentAsString());
    if (FJsonSerializer::Deserialize(OuterReader, OuterJsonObject) && OuterJsonObject.IsValid())
    {
        FString BodyString;
        if (OuterJsonObject->TryGetStringField(TEXT("body"), BodyString))
        {
            TSharedPtr<FJsonObject> InnerJsonObject;
            TSharedRef<TJsonReader<>> InnerReader = TJsonReaderFactory<>::Create(BodyString);
            if (FJsonSerializer::Deserialize(InnerReader, InnerJsonObject) && InnerJsonObject.IsValid())
            {
                FString PlayerURL, HomeAreaURL;
                if (InnerJsonObject->TryGetStringField(TEXT("playerDownloadUrl"), PlayerURL) && InnerJsonObject->TryGetStringField(TEXT("homeAreaDownloadUrl"), HomeAreaURL))
                {
                    PendingDownloads = 2;
                    DownloadDataFromS3(PlayerURL);
                    DownloadDataFromS3(HomeAreaURL);
                    return;
                }
            }
        }
    }
    OnLoadFromS3Complete.Broadcast(false, nullptr, nullptr);
}

